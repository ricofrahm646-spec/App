class IndicatorGenerator:
    """Generates MQL5 custom indicator source files."""

    def __init__(self) -> None:
        self._env = Environment(
            loader=BaseLoader(),
            keep_trailing_newline=True,
            trim_blocks=True,
            lstrip_blocks=True,
        )
        self._template = self._env.from_string(_INDICATOR_TEMPLATE)

    def generate(self, config: IndicatorConfig) -> str:
        """Render the indicator template with the given configuration."""
        ctx = self._build_context(config)
        return self._template.render(**ctx)

    def generate_to_file(self, config: IndicatorConfig, output_path: Path) -> Path:
        """Generate indicator and write the .mq5 file."""
        code = self.generate(config)
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(code, encoding="utf-8")
        logger.info("Indicator written to %s (%d bytes)", output_path, len(code))
        return output_path

    def generate_preset(self, indicator_type: IndicatorType, name: Optional[str] = None) -> str:
        """Generate a preset indicator by type."""
        preset = INDICATOR_PRESETS.get(indicator_type)
        if not preset:
            raise ValueError(f"No preset for indicator type: {indicator_type}")

        config = IndicatorConfig(
            name=name or f"JARVIS_{indicator_type.value}",
            indicator_type=indicator_type,
            buffers=preset["buffers"],
            inputs=preset.get("inputs", ""),
            window=preset.get("window", "indicator_chart_window"),
            on_calculate_body=preset.get("on_calculate_body", ""),
            levels=preset.get("levels", []),
            minimum=preset.get("minimum"),
            maximum=preset.get("maximum"),
        )
        return self.generate(config)

    def list_indicator_types(self) -> List[str]:
        """Return available indicator type names."""
        return [t.value for t in IndicatorType]

    def _build_context(self, config: IndicatorConfig) -> Dict[str, Any]:
        preset = INDICATOR_PRESETS.get(config.indicator_type, {})

        buffers = config.buffers or preset.get("buffers", [])
        if not buffers:
            buffers = [BufferSpec("Value", config.name)]

        return {
            "name": config.name,
            "short_name": config.short_name or config.name,
            "window": config.window or preset.get("window", "indicator_chart_window"),
            "buffers": buffers,
            "buffer_count": len(buffers),
            "plot_count": len(buffers),
            "inputs": config.inputs or preset.get("inputs", ""),
            "on_init_extra": config.on_init_extra,
            "on_deinit_extra": config.on_deinit_extra,
            "on_calculate_body": config.on_calculate_body or preset.get("on_calculate_body", ""),
            "custom_functions": config.custom_functions,
            "levels": config.levels if config.levels else preset.get("levels", []),
            "minimum": config.minimum if config.minimum is not None else preset.get("minimum"),
            "maximum": config.maximum if config.maximum is not None else preset.get("maximum"),
        }
