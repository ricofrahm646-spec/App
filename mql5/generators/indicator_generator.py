_MA_CALC = """\
   int start = (prev_calculated > 0) ? prev_calculated - 1 : InpMAPeriod;

   for(int i = start; i < rates_total; i++)
   {
      double sum = 0;
      for(int j = 0; j < InpMAPeriod && (i - j) >= 0; j++)
         sum += close[i - j];
      MABuffer[i] = sum / InpMAPeriod;
   }"""

_MA_INPUTS = """\
input int InpMAPeriod = 14;  // MA Period"""


_RSI_CALC = """\
   int start = (prev_calculated > 0) ? prev_calculated - 1 : InpRSIPeriod + 1;

   for(int i = start; i < rates_total; i++)
   {
      double gainSum = 0, lossSum = 0;
      for(int j = 1; j <= InpRSIPeriod && (i - j) >= 0; j++)
      {
         double change = close[i - j + 1] - close[i - j];
         if(change > 0) gainSum += change;
         else           lossSum += MathAbs(change);
      }
      double avgGain = gainSum / InpRSIPeriod;
      double avgLoss = lossSum / InpRSIPeriod;
      if(avgLoss == 0)
         RSIBuffer[i] = 100.0;
      else
         RSIBuffer[i] = 100.0 - (100.0 / (1.0 + avgGain / avgLoss));
   }"""

_RSI_INPUTS = """\
input int InpRSIPeriod = 14;  // RSI Period"""


_BB_CALC = """\
   int start = (prev_calculated > 0) ? prev_calculated - 1 : InpBBPeriod;

   for(int i = start; i < rates_total; i++)
   {
      double sum = 0;
      for(int j = 0; j < InpBBPeriod && (i - j) >= 0; j++)
         sum += close[i - j];
      double ma = sum / InpBBPeriod;

      double sumSq = 0;
      for(int j = 0; j < InpBBPeriod && (i - j) >= 0; j++)
         sumSq += MathPow(close[i - j] - ma, 2);
      double stddev = MathSqrt(sumSq / InpBBPeriod);

      MiddleBuffer[i] = ma;
      UpperBuffer[i]  = ma + InpBBDeviation * stddev;
      LowerBuffer[i]  = ma - InpBBDeviation * stddev;
   }"""

_BB_INPUTS = """\
input int    InpBBPeriod    = 20;   // BB Period
input double InpBBDeviation = 2.0;  // BB Deviation"""


_MACD_CALC = """\
   int start = (prev_calculated > 0) ? prev_calculated - 1 : InpSlowEMA;

   // Simple EMA approximation
   double fastK = 2.0 / (InpFastEMA + 1);
   double slowK = 2.0 / (InpSlowEMA + 1);
   double sigK  = 2.0 / (InpSignalSMA + 1);

   static double fastEMA = 0, slowEMA = 0, signalEMA = 0;
   if(prev_calculated == 0)
   {
      fastEMA = close[0]; slowEMA = close[0]; signalEMA = 0;
   }

   for(int i = start; i < rates_total; i++)
   {
      fastEMA = close[i] * fastK + fastEMA * (1 - fastK);
      slowEMA = close[i] * slowK + slowEMA * (1 - slowK);
      MACDBuffer[i] = fastEMA - slowEMA;
      signalEMA = MACDBuffer[i] * sigK + signalEMA * (1 - sigK);
      SignalBuffer[i] = signalEMA;
   }"""

_MACD_INPUTS = """\
input int InpFastEMA   = 12;  // Fast EMA Period
input int InpSlowEMA   = 26;  // Slow EMA Period
input int InpSignalSMA = 9;   // Signal SMA Period"""


_ATR_CALC = """\
   int start = (prev_calculated > 0) ? prev_calculated - 1 : InpATRPeriod + 1;

   for(int i = start; i < rates_total; i++)
   {
      double trSum = 0;
      for(int j = 0; j < InpATRPeriod && (i - j) >= 1; j++)
      {
         double tr = MathMax(high[i-j] - low[i-j],
                    MathMax(MathAbs(high[i-j] - close[i-j-1]),
                            MathAbs(low[i-j] - close[i-j-1])));
         trSum += tr;
      }
      ATRBuffer[i] = trSum / InpATRPeriod;
   }"""

_ATR_INPUTS = """\
input int InpATRPeriod = 14;  // ATR Period"""


_STOCH_CALC = """\
   int start = (prev_calculated > 0) ? prev_calculated - 1 : InpKPeriod;

   for(int i = start; i < rates_total; i++)
   {
      double highest = high[i], lowest = low[i];
      for(int j = 0; j < InpKPeriod && (i - j) >= 0; j++)
      {
         if(high[i-j] > highest) highest = high[i-j];
         if(low[i-j] < lowest)   lowest  = low[i-j];
      }
      if(highest - lowest > 0)
         KBuffer[i] = (close[i] - lowest) / (highest - lowest) * 100.0;
      else
         KBuffer[i] = 50.0;
   }

   // %D = SMA of %K
   for(int i = start; i < rates_total; i++)
   {
      double sum = 0;
      int cnt = 0;
      for(int j = 0; j < InpDPeriod && (i - j) >= 0; j++)
      {
         sum += KBuffer[i - j];
         cnt++;
      }
      DBuffer[i] = (cnt > 0) ? sum / cnt : 50.0;
   }"""

