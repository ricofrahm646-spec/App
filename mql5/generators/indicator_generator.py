"""Custom MQL5 indicator code generator."""
import logging
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional

from jinja2 import Environment, BaseLoader

logger = logging.getLogger(__name__)


class DrawingStyle(Enum):
    LINE = "DRAW_LINE"
    HISTOGRAM = "DRAW_HISTOGRAM"
    ARROW = "DRAW_ARROW"
    SECTION = "DRAW_SECTION"
    ZIGZAG = "DRAW_ZIGZAG"
    COLOR_LINE = "DRAW_COLOR_LINE"
    FILLING = "DRAW_FILLING"
    NONE = "DRAW_NONE"


class IndicatorType(Enum):
    MOVING_AVERAGE = "moving_average"
    RSI = "rsi"
    BOLLINGER_BANDS = "bollinger_bands"
    MACD = "macd"
    ATR = "atr"
    STOCHASTIC = "stochastic"
    CUSTOM = "custom"


@dataclass
class BufferSpec:
    """Specification for a single indicator buffer."""
    name: str
    label: str = ""
    style: DrawingStyle = DrawingStyle.LINE
    color: str = "clrDodgerBlue"
    width: int = 1
    line_style: str = "STYLE_SOLID"


@dataclass
class IndicatorConfig:
    """Configuration for generating a custom indicator."""
    name: str = "JARVIS_Indicator"
    indicator_type: IndicatorType = IndicatorType.CUSTOM
    short_name: str = ""
    buffers: List[BufferSpec] = field(default_factory=list)
    inputs: str = ""
    window: str = "indicator_chart_window"
    on_calculate_body: str = ""
    on_init_extra: str = ""
    on_deinit_extra: str = ""
    custom_functions: str = ""
    levels: List[float] = field(default_factory=list)
    minimum: Optional[float] = None
    maximum: Optional[float] = None


