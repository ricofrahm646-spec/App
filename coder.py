"""
coder.py
========
J.A.R.V.I.S. V300 - Code-Forge.

Generates self-contained Python applications in :data:`APPS_DIR` based on
short natural-language specs. The generator is **deterministic and
template-driven**, not an LLM, so it produces error-free code every time and
plays well with the security-auditor in ``ghost_security.py``.

Supported scaffolds out of the box:

    * cli         - argparse-based CLI tool with logging.
    * api         - FastAPI service skeleton with /health, /predict endpoints.
    * scraper     - requests + bs4 + JSON output.
    * bot         - polling worker loop with backoff.
    * streamlit   - Streamlit dashboard skeleton.
    * dataclass   - simple data-class library + tests.

After generating the code, the new file is:

    1. byte-compiled via :pymod:`py_compile` to catch syntax errors.
    2. auto-formatted via ``black`` if it is importable, otherwise left as-is.
    3. handed to :func:`ghost_security.audit_file` for an automatic audit.

The result is logged to the event bus and returned to the caller.
"""
