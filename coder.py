# ---------------------------------------------------------------------------
# Spec parsing
# ---------------------------------------------------------------------------
@dataclass
class GenerationResult:
    path: Path
    template: str
    ok: bool
    error: str = ""
    audit_findings: int = 0


_SLUG_RE = re.compile(r"[^a-z0-9_]+")


def _slugify(text: str) -> str:
    s = _SLUG_RE.sub("_", text.lower()).strip("_")
    return s or f"app_{int(_dt.datetime.now(_tz.utc).timestamp())}"


def _pick_template(spec: str) -> str:
    s = spec.lower()
    if any(w in s for w in ("api", "rest", "endpoint", "fastapi")):
        return "api"
    if any(w in s for w in ("scrape", "scraper", "crawl", "fetch")):
        return "scraper"
    if any(w in s for w in ("bot", "worker", "loop", "daemon")):
        return "bot"
    if any(w in s for w in ("dashboard", "streamlit", "ui", "panel")):
        return "streamlit"
    if any(w in s for w in ("model", "schema", "dataclass", "library")):
        return "dataclass"
    return "cli"


# ---------------------------------------------------------------------------
# Generator
# ---------------------------------------------------------------------------
def generate_app(spec: str, name: str | None = None) -> GenerationResult:
    """Generate a Python application in :data:`APPS_DIR` based on ``spec``.

    Returns a :class:`GenerationResult`. Always writes a file even if
    formatting/audit steps fail - the only reason ``ok`` will be False is if
    py_compile rejects the result.
    """
    APPS_DIR.mkdir(parents=True, exist_ok=True)
    template = _pick_template(spec)
    slug = _slugify(name or (spec.split()[0] if spec.split() else "app"))
    # Avoid file names that collide with installed packages such as
    # ``fastapi``, ``streamlit``, ``requests`` etc.
    RESERVED = {"fastapi", "streamlit", "requests", "playwright", "numpy",
                "pandas", "cv2", "opencv", "mss", "pyautogui", "pickle"}
    if slug in RESERVED or not slug.endswith(template):
        slug = f"jarvis_{slug}_{template}"
    path = APPS_DIR / f"{slug}.py"
    code = _header(slug, spec) + TEMPLATES[template].format(
        name=slug, slug=slug, description=spec.replace("\n", " ").strip()[:160] or "Generated app",
    ).lstrip()
    path.write_text(code, encoding="utf-8")

    try:
        py_compile.compile(str(path), doraise=True)
        ok, err = True, ""
    except py_compile.PyCompileError as exc:
        ok, err = False, str(exc)

    findings = 0
    if ghost_security is not None:
        try:
            audit = ghost_security.audit_file(path)
            findings = len(audit)
            if audit:
                ghost_security.write_audit_report(audit)
        except Exception as exc:
            bus.log("coder", f"audit-after-generation failed: {exc}", level="WARN")

    bus.log(
        "coder",
        f"forged {path.name} template={template} ok={ok} findings={findings}",
        level="INFO" if ok else "ERROR",
    )
    return GenerationResult(path=path, template=template, ok=ok, error=err, audit_findings=findings)


def list_apps() -> List[Path]:
    return sorted(APPS_DIR.glob("*.py"))


if __name__ == "__main__":
    import sys
    spec = " ".join(sys.argv[1:]) or "demo cli app that prints hello"
    res = generate_app(spec)
    print(f"Generated: {res.path}  ok={res.ok}  template={res.template}")
    if res.error:
        print("ERROR:", res.error)
