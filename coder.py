def _header(name: str, description: str) -> str:
    return textwrap.dedent(f'''
        """
        {name}
        {"=" * len(name)}
        Auto-generated by J.A.R.V.I.S. Code-Forge on {_dt.datetime.now(_tz.utc).isoformat()}.

        {description}
        """
    ''').lstrip()


