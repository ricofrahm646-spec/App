# ── AI Code Generator ───────────────────────────────────────────────────────

class AICodeGenerator:
    """Uses OpenAI to generate Python code from natural language."""

    def __init__(self):
        self.client = None
        if OPENAI_AVAILABLE and OPENAI_API_KEY:
            self.client = openai.OpenAI(api_key=OPENAI_API_KEY)

    def generate(self, spec: str, app_name: str) -> Optional[str]:
        if not self.client:
            logger.info("OpenAI unavailable — using template-based generation")
            return None

        system_prompt = textwrap.dedent("""
            You are J.A.R.V.I.S. V300 Coder Engine — an elite Python code generator.

            Rules:
            - Generate complete, production-ready Python code
            - Include proper error handling and logging
            - Use type hints throughout
            - Include a docstring at the top
            - Make the code self-contained with a __main__ block
            - Follow PEP 8 strictly
            - Never use eval() or exec()
            - Never hardcode secrets — use environment variables
            - Add "Generated by J.A.R.V.I.S. V300" in the module docstring
        """)

        try:
            response = self.client.chat.completions.create(
                model=OPENAI_MODEL,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": f"App name: {app_name}\n\nSpecification:\n{spec}"},
                ],
                temperature=0.3,
                max_tokens=4000,
            )
            code = response.choices[0].message.content
            code = self._extract_python(code)
            return code
        except Exception as e:
            logger.error(f"AI generation failed: {e}")
            return None

    @staticmethod
    def _extract_python(text: str) -> str:
        if "```python" in text:
            parts = text.split("```python")
            if len(parts) > 1:
                code = parts[1].split("```")[0]
                return code.strip()
        if "```" in text:
            parts = text.split("```")
            if len(parts) > 1:
                return parts[1].strip()
        return text.strip()


# ── Coder Engine ─────────────────────────────────────────────────────────────

class CoderEngine:
    """Main code generation engine — template + AI hybrid."""

    def __init__(self):
        self.ai = AICodeGenerator()
        self.scanner = SecurityScanner()
        self.apps_built = 0
        self.errors = 0

    def create_app(self, name: str, description: str,
                   app_type: str = "cli_tool", spec: str = "") -> dict:
        logger.info(f"Coder: Generating '{name}' ({app_type})")

        code = None
        method = "template"

        if spec and self.ai.client:
            code = self.ai.generate(spec, name)
            if code:
                method = "ai"

        if not code:
            template = TEMPLATES.get(app_type, TEMPLATES["cli_tool"])
            code = template.format(name=name, description=description)

        issues = self.scanner.scan_code_string(code, name)
        critical = [i for i in issues if i["severity"] in ("CRITICAL", "HIGH")]

        if critical:
            logger.warning(f"Security issues in generated code: {len(critical)} critical/high")
            self.errors += len(critical)
            return {
                "success": False,
                "name": name,
                "method": method,
                "issues": critical,
                "message": "Code rejected — security issues found",
            }

        try:
            ast.parse(code)
        except SyntaxError as e:
            self.errors += 1
            return {
                "success": False,
                "name": name,
                "method": method,
                "issues": [{"severity": "ERROR", "message": str(e)}],
                "message": f"Syntax error: {e}",
            }

        safe_name = "".join(c if c.isalnum() or c == "_" else "_" for c in name.lower())
        filepath = APPS_DIR / f"{safe_name}.py"
        filepath.write_text(code)

        self.apps_built += 1
        logger.info(f"App created: {filepath} (method={method}, issues={len(issues)})")

        return {
            "success": True,
            "name": name,
            "path": str(filepath),
            "method": method,
            "issues": issues,
            "message": f"App '{name}' deployed to {filepath}",
        }

    def list_apps(self) -> list[dict]:
        apps = []
        for f in APPS_DIR.glob("*.py"):
            stat = f.stat()
            apps.append({
                "name": f.stem,
                "path": str(f),
                "size": stat.st_size,
                "modified": datetime.fromtimestamp(stat.st_mtime).isoformat(),
            })
        return apps

    def test_app(self, app_path: str) -> dict:
        try:
            result = subprocess.run(
                [sys.executable, "-c", f"import ast; ast.parse(open('{app_path}').read())"],
                capture_output=True, text=True, timeout=10,
            )
            return {
                "path": app_path,
                "syntax_valid": result.returncode == 0,
                "error": result.stderr if result.returncode != 0 else None,
            }
        except Exception as e:
            return {"path": app_path, "syntax_valid": False, "error": str(e)}

    def get_status(self) -> dict:
        return {
            "status": "ACTIVE",
            "apps_built": self.apps_built,
            "errors": self.errors,
        }


