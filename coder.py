"""
Code generation scaffold for new Python apps under /apps.
Implements safe defaults: typed entrypoint, logging, no network exfiltration hooks.
Extend with your own LLM provider by setting CODER_PROVIDER=ollama|openai and API keys.
"""
from __future__ import annotations

import json
import os
import re
import textwrap
import urllib.error
import urllib.request
from pathlib import Path
from typing import Literal

from config import APPS_DIR, LOGS_DIR

LOGS_DIR.mkdir(parents=True, exist_ok=True)

Slug = str


def _slugify(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]+", "_", name.strip()).strip("_").lower()
    return s or "app"


def app_boilerplate(title: str, description: str) -> str:
    """Deterministic, lint-friendly starter app."""
    safe_title = title.replace('"', "'")
    safe_desc = (description or "").replace('"', "'")[:500]
    return textwrap.dedent(
        f'''\
        """
        {safe_title}
        {safe_desc}
        Generated by coder.py — review before production use.
        """
        from __future__ import annotations

        import logging
        import sys
        from pathlib import Path

        logging.basicConfig(
            level=logging.INFO,
            format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
        )
        log = logging.getLogger("{_slugify(title)}")

        def main() -> int:
            log.info("Starting %s", "{safe_title}")
            # TODO: implement domain logic here
            return 0

        if __name__ == "__main__":
            sys.exit(main())
        '''
    )


def write_app(slug: Slug, title: str, description: str) -> Path:
    slug = _slugify(slug)
    base = APPS_DIR / slug
    base.mkdir(parents=True, exist_ok=True)
    main_py = base / "main.py"
    main_py.write_text(app_boilerplate(title, description), encoding="utf-8")
    (base / "__init__.py").write_text("", encoding="utf-8")
    return main_py


def run_llm_enhancement(path: Path, instruction: str) -> str | None:
    """Optional: Ollama local model to refine code. Returns error message on failure."""
    provider = os.getenv("CODER_PROVIDER", "").lower()
    if provider != "ollama":
        return None
    model = os.getenv("OLLAMA_MODEL", "llama3.2")
    host = os.getenv("OLLAMA_HOST", "http://127.0.0.1:11434").rstrip("/")
    prompt = (
        "Improve this Python file. Only output valid Python code, no markdown.\n\n"
        f"{instruction}\n\n"
        f"{path.read_text(encoding='utf-8')}"
    )
    body = json.dumps({"model": model, "prompt": prompt, "stream": False}).encode("utf-8")
    req = urllib.request.Request(
        f"{host}/api/generate",
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        code = (data.get("response") or "").strip()
        if code.startswith("```"):
            code = code.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
        if code:
            path.write_text(code, encoding="utf-8")
        return None
    except urllib.error.URLError as exc:
        return str(exc)
    except Exception as exc:  # noqa: BLE001
        return str(exc)


def generate_app(
    slug: str,
    title: str,
    description: str,
    *,
    enhance: Literal["none", "ollama"] = "none",
) -> Path:
    path = write_app(slug, title, description)
    if enhance == "ollama":
        err = run_llm_enhancement(path, "Refactor for clarity and add argparse for CLI flags.")
        if err:
            (LOGS_DIR / "coder_llm_errors.log").open("a", encoding="utf-8").write(err + "\n")
    return path.parent
