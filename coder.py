from __future__ import annotations

import re
import textwrap
from dataclasses import asdict, dataclass
from pathlib import Path

from ghost_security import GhostSecurity


@dataclass(slots=True)
class GeneratedApp:
    name: str
    template: str
    path: str
    audit: dict

    def to_dict(self) -> dict:
        return asdict(self)


class JarvisCoder:
    def __init__(self, workspace_root: str | Path) -> None:
        self.workspace_root = Path(workspace_root)
        self.apps_dir = self.workspace_root / "apps"
        self.apps_dir.mkdir(parents=True, exist_ok=True)
        self.security = GhostSecurity(self.workspace_root)

    @staticmethod
    def sanitize_name(name: str) -> str:
        safe = re.sub(r"[^a-zA-Z0-9_]+", "_", name.strip().lower())
        return safe.strip("_") or "jarvis_app"

    def infer_template(self, specification: str) -> str:
        spec = specification.lower()
        if any(token in spec for token in ("dashboard", "streamlit", "visual")):
            return "streamlit_dashboard"
        if any(token in spec for token in ("api", "http", "client", "request")):
            return "api_client"
        if any(token in spec for token in ("worker", "queue", "job", "monitor")):
            return "worker"
        return "cli_tool"

    def render_template(self, app_name: str, specification: str, template: str) -> str:
        title = app_name.replace("_", " ").title()
        if template == "streamlit_dashboard":
            return textwrap.dedent(
                f'''\
                import streamlit as st
                import pandas as pd
                import plotly.express as px

                st.set_page_config(page_title="{title}", layout="wide")
                st.title("{title}")
                st.caption("Generated by JARVIS Coder")

                st.write("""{specification}""")

                data = pd.DataFrame(
                    {{
                        "step": [1, 2, 3, 4, 5],
                        "value": [12, 18, 14, 24, 31],
                    }}
                )
                chart = px.line(data, x="step", y="value", markers=True, title="{title} - Live Curve")
                st.plotly_chart(chart, use_container_width=True)
                st.dataframe(data, use_container_width=True)
                '''
            )

        if template == "api_client":
            return textwrap.dedent(
                f'''\
                from __future__ import annotations

                import requests


                def fetch_status(url: str) -> dict:
                    response = requests.get(url, timeout=10)
                    response.raise_for_status()
                    content_type = response.headers.get("content-type", "")
                    if "json" in content_type:
                        return response.json()
                    return {{"text": response.text[:500]}}


                if __name__ == "__main__":
                    print(fetch_status("https://httpbin.org/json"))
                '''
            )

        if template == "worker":
            return textwrap.dedent(
                f'''\
                from __future__ import annotations

                import time
                from dataclasses import dataclass


                @dataclass
                class JobResult:
                    iteration: int
                    message: str


                def run_worker(cycles: int = 5) -> list[JobResult]:
                    results = []
                    for index in range(1, cycles + 1):
                        results.append(JobResult(iteration=index, message="Processed cycle"))
                        time.sleep(0.1)
                    return results


                if __name__ == "__main__":
                    print(run_worker())
                '''
            )

        return textwrap.dedent(
            f'''\
            from __future__ import annotations

            import argparse


            def main() -> None:
                parser = argparse.ArgumentParser(description="{title}")
                parser.add_argument("--name", default="Sir", help="Name for the greeting target")
                args = parser.parse_args()
                print(f"{title} ready for {{args.name}}")
                print("""{specification}""")


            if __name__ == "__main__":
                main()
            '''
        )

    def generate_app(self, app_name: str, specification: str) -> GeneratedApp:
        safe_name = self.sanitize_name(app_name)
        template = self.infer_template(specification)
        content = self.render_template(safe_name, specification, template)
        app_path = self.apps_dir / f"{safe_name}.py"
        app_path.write_text(content, encoding="utf-8")
        audit = self.security.audit_file(app_path)
        return GeneratedApp(name=safe_name, template=template, path=str(app_path), audit=audit)

    def list_apps(self) -> list[str]:
        return sorted(str(path.name) for path in self.apps_dir.glob("*.py"))


if __name__ == "__main__":
    coder = JarvisCoder(Path.cwd())
    generated = coder.generate_app("ops_dashboard", "A visual dashboard for operations with Streamlit charts.")
    print(generated.to_dict())
