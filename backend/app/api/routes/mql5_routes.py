# ── Compile ──────────────────────────────────────────────────────────────

@router.post(
    "/compile",
    response_model=APIResponse,
    summary="Compile MQL5 source code",
)
async def compile_mql5(request: MQL5CompileRequest) -> APIResponse:
    logger.info("mql5_compile", filename=request.filename)

    errors: list[str] = []
    warnings: list[str] = []

    if "#property" not in request.code:
        warnings.append("Missing #property directives.")
    if "OnInit" not in request.code and "OnCalculate" not in request.code:
        errors.append("No entry point found (OnInit or OnCalculate required).")
    if "OnTick" not in request.code and "OnCalculate" not in request.code:
        warnings.append("No OnTick or OnCalculate handler found.")

    result = MQL5CompileResponse(
        success=len(errors) == 0,
        filename=request.filename.replace(".mq5", ".ex5"),
        errors=errors,
        warnings=warnings,
    )

    if result.success:
        logger.info("mql5_compile_success", filename=request.filename)
    else:
        logger.warning(
            "mql5_compile_failed",
            filename=request.filename,
            errors=errors,
        )

    return APIResponse(
        success=result.success,
        message="Compilation successful." if result.success else "Compilation failed.",
        data=result.model_dump(mode="json"),
    )


# ── Install to MT5 ──────────────────────────────────────────────────────

@router.post(
    "/install",
    response_model=APIResponse,
    summary="Install compiled file to MT5 terminal",
)
async def install_to_mt5(request: MQL5InstallRequest) -> APIResponse:
    logger.info(
        "mql5_install",
        filename=request.filename,
        type=request.mql_type.value,
    )

    type_dirs = {
        MQL5Type.EA: "Experts",
        MQL5Type.INDICATOR: "Indicators",
        MQL5Type.SCRIPT: "Scripts",
    }
    target_dir = type_dirs.get(request.mql_type, "Experts")

    return APIResponse(
        success=True,
        message=f"File '{request.filename}' queued for installation to MQL5/{target_dir}/.",
        data={
            "filename": request.filename,
            "target_directory": f"MQL5/{target_dir}/",
            "status": "queued",
        },
    )


# ── List generated files ────────────────────────────────────────────────

@router.get(
    "/files",
    response_model=APIResponse,
    summary="List all generated MQL5 files",
)
async def list_generated_files() -> APIResponse:
    items = [
        {"filename": f.filename, "type": f.mql_type.value}
        for f in _generated_files.values()
    ]
    return APIResponse(success=True, data=items)


# ── Get generated file ──────────────────────────────────────────────────

@router.get(
    "/files/{filename}",
    response_model=APIResponse,
    summary="Get a generated MQL5 file",
)
async def get_generated_file(filename: str) -> APIResponse:
    result = _generated_files.get(filename)
    if not result:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"File '{filename}' not found.",
        )
    return APIResponse(success=True, data=result.model_dump(mode="json"))
